function line(
  id: string,
  mode: Mode,
  color: string,
  ids: string[],
  frequency: number | null,
  status: ServiceStatus = "normal",
  statusNote = "Service régulier dans ce scénario de démonstration.",
): Line {
  const first = stops.find((s) => s.id === ids[0])!;
  const last = stops.find((s) => s.id === ids.at(-1))!;
  return {
    id,
    mode,
    color,
    name: `${first.name} → ${last.name}`,
    stops: ids,
    frequency,
    start: "05:30",
    end: "22:00",
    status,
    statusNote,
    bidirectional: mode !== "bus",
  };
}
